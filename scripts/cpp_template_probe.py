BASELINE = {
 'lib/cppcheck.cpp':'377cde381b0f6b3b4ea55ec8beeea4691992628f18589e8238f344e49ba078bd',
 'lib/tokenize.cpp':'76beaa920046dbe057c5b20b09c043802351692657e2b3f269cf4612984eac88',
 'lib/templatesimplifier.cpp':'61e6d1c8be0327fe8689c132b95ad519d95685e88d9766e8862e625b80e11d4f',
}
# Generated by pinned, reversible insertions; never inferred from a runtime receipt.
AFTER = {
 'lib/cppcheck.cpp':'3dd79cefdedebb75f4f28d81fb52409efcdc0f51e418451fdee865ca98f1eaff',
 'lib/tokenize.cpp':'dea56ed2255b18f622ee8fc35274880843595d308c5677387b2dce5b24b8b9c6',
 'lib/templatesimplifier.cpp':'559b3e1430ffb58b4001cda5937873977a0351f63ca3d46029a37b361bfd1970',
}

def digest(raw):return hashlib.sha256(raw).hexdigest()

def instrument_baseline(relative,raw):
    if relative not in BASELINE or digest(raw)!=BASELINE[relative]:raise ValueError('template_probe_source_identity')
    # Private build-process module state only; restore even when anchor checks fail.
    if relative=='lib/cppcheck.cpp':return boundaries.overlay_later_stages(raw)
    prior=instrument.SOURCE_SHA256
    try:
        instrument.SOURCE_SHA256=BASELINE
        result=instrument.instrument(relative,raw)
    finally:instrument.SOURCE_SHA256=prior
    if relative=='lib/tokenize.cpp':result=boundaries.overlay_subphases(result)
    restored=instrument.strip_instrumentation(boundaries.strip(result))
    if restored!=raw:raise ValueError('template_probe_semantic_source_changed')
    return result

def expected_receipt():
    return {'schema':'nico.cpp-template-probe-overlay.v1','source_sha256':BASELINE,
        'instrumented_source_sha256':AFTER,'restored_source_sha256':BASELINE,
        'script_sha256':digest(Path(__file__).read_bytes()),
        'instrument_script_sha256':digest(Path(instrument.__file__).read_bytes()),
        'boundary_script_sha256':digest(Path(boundaries.__file__).read_bytes()),
        'header_sha256':digest(instrument.HEADER.read_bytes()),
        'grouping_applied':False,'instrumentation_only':True,'qualification_credit':False}

def apply_to_source(source):
    source=Path(source)
    prepared={}
    for relative in BASELINE:
        raw=instrument.read_regular(source/relative)
        result=instrument_baseline(relative,raw)
        if digest(result)!=AFTER[relative]:raise ValueError('template_probe_output_identity')
        prepared[relative]=result
    for relative,result in prepared.items():(source/relative).write_bytes(result)
    (source/'lib/nico_stage_counters.h').write_bytes(instrument.HEADER.read_bytes())
    return expected_receipt()


# Console projection only. Raw prefixes remain in their fresh execution evidence.
COUNT_FIELDS=('pass','using_calls','active_bucket','transition_id','transition_saturated',
 'selection_entered','selection_completed','matching_entered','matching_completed',
 'expansion_entered','expansion_completed','replacement_entered','replacement_completed',
 'selection_visits','specialization_visits','specialization_token_visits',
 'expansion_outer_visits','expansion_body_visits','replacement_visits','replacement_nested_visits',
 'stable_selection_ns','stable_matching_ns','stable_expansion_ns','stable_replacement_ns',
 'unattributed_ns','outside_ns','observer_ns','thread_clock_status','interval_ns','interval_kind')
DELTA_FIELDS=('transition_id','using_calls','selection_visits','specialization_visits',
              'expansion_outer_visits','replacement_visits')

def unknown_summary(state='unavailable'):
    return {'state':state,'precise_termination_hotspot_known':False}

def summarize_prefix(raw,*,binary_sha256,timed_out,output_truncated):
    if output_truncated:return unknown_summary('truncated')
    if not isinstance(raw,bytes) or len(raw)>65536:return unknown_summary()
    try:
        from scripts.native_stage_counters.evidence import parse_snapshots
        parsed=parse_snapshots(raw,timed_out=timed_out,binary_sha256=binary_sha256,
                               output_truncated=False,expected_version=3)
        rows=parsed['records']
        if parsed['incomplete_tail']:return unknown_summary('invalid')
        if len(rows)>=128:return unknown_summary('capped')
        if not rows:return unknown_summary()
        row=rows[-1]
        deltas=None
        if len(rows)>1 and rows[-2]['lane']==row['lane']:
            previous=rows[-2]
            if all(row[k]>=previous[k] for k in DELTA_FIELDS):
                deltas={key:row[key]-previous[key] for key in DELTA_FIELDS}
        return {**unknown_summary('observed_prefix'),'records':len(rows),
            'last_sample_wall_us_since_probe_start':row['wall_us'],
            'sample_age_state':'unavailable','last_interval_deltas':deltas,
            'cpu_attribution':'stable_intervals_only_mixed_unattributed_prefix_tail_unknown',
            **{key:row[key] for key in COUNT_FIELDS}}
    except (ValueError,TypeError,KeyError):return unknown_summary('invalid')

def valid_summary(value):
    if type(value) is not dict or value.get('precise_termination_hotspot_known') is not False:return False
    state=value.get('state')
    if state in {'unavailable','invalid','capped','truncated','omitted'}:
        return set(value)==set(unknown_summary())
    if state!='observed_prefix':return False
    if set(value)!=set(unknown_summary())|set(COUNT_FIELDS)|{'records','last_sample_wall_us_since_probe_start','sample_age_state','cpu_attribution','last_interval_deltas'}:return False
    if value['sample_age_state']!='unavailable' or value['cpu_attribution']!='stable_intervals_only_mixed_unattributed_prefix_tail_unknown':return False
    for key,allowed in {'pass':range(11),'active_bucket':range(5),'transition_saturated':(0,1),
                        'thread_clock_status':(1,2),'interval_kind':range(8)}.items():
        if type(value[key]) is not int or value[key] not in allowed:return False
    deltas=value['last_interval_deltas']
    if deltas is not None and (type(deltas) is not dict or set(deltas)!=set(DELTA_FIELDS)
            or any(type(v) is not int or not 0<=v<2**64 for v in deltas.values())):return False
    if type(value['records']) is not int or not 1<=value['records']<128:return False
    return all(type(value[k]) is int and 0<=value[k]<2**64 for k in (*COUNT_FIELDS,'last_sample_wall_us_since_probe_start'))


